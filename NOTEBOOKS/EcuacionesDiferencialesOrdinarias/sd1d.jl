md"""
## $\cdot$ Primer ejemplo

Las ecuaciones diferenciales de primer orden tienen la siguiente forma

$\dfrac{dy}{dx}=f(x,y).$

Un ejemplo sencillo de esto es

$\frac{d}{dt}x(t)=a x(t),$
donde $a$ es una constante. Es fácil ver que las soluciones de esta ecuación son de la forma 

$x=Ce^{at},$
donde $C$ es una constante que depende de las condiciones iniciales $x(0)=x_0$. Si consideramos $a=-0.1$ y $x_0=1$ se tiene el siguiente problema

$\frac{d}{dt}x(t)=-0.1 x(t),\hspace{1.5cm}x(0)=1.$
Así, la solución de este problema es de la forma 

$x=Ce^{-0.1t},$
y de la condición inicial se obtiene que $C=1$, por tanto

$x=e^{-0.1t}.$"""

# ╔═╡ 40205f35-a035-428e-b7ef-d023768bbb2e
md"""Esto también lo podemos solucionar de la siguiente forma, creando una función que retorne el lado derecho (o forzante) de la EDO de primer orden un su forma canónica."""

# ╔═╡ 9c99e1e7-a2a6-4735-ae1f-267259d6d50e
f(x,p,t) = -0.1 * x #Definimos la ecuación diferencial

# ╔═╡ d0600137-a0f4-49b6-983d-24f3c1f48713
md"""También definimos la condición inicial y el tiempo inicial y final."""

# ╔═╡ c63063ab-58ad-4032-8a9a-0af1cb4828d8
@bind u0 Slider(-5:5, show_value=true)

# ╔═╡ 6cb2c1a0-2894-4079-81b0-0302f86ae2e7
