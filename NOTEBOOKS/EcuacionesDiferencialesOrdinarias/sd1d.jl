md""" 
## $\cdot$ Un sistema $2\times 2$
Los sistemas de ecuaciones diferenciales son conjuntos de ecuaciones que describen cómo cambian varias cantidades en función del tiempo o de otras variables independientes. Cada ecuación en el sistema representa una tasa de cambio para una de las cantidades, y todas estas cantidades están relacionadas entre sí. Resolver un sistema de ecuaciones diferenciales implica encontrar funciones que satisfagan todas las ecuaciones simultáneamente.

Considere el siguiente sistema de dos ecuaciones diferenciales con dos incognitas funcionales, 

$$\left \{ \begin{array}{rcl]}
x'_1 &=& 3x_1 + 4x_2 - \sin(t),\\
x'_2 &=& -x_1 + 2x_2 - t^2,\\
x_1(0) &=& 1,\\
x_2(0) &=& -1.
\end{array}\right.$$

A continuación se muestra como se soluciona."""

# ╔═╡ c0bd9c3e-ab2e-4920-bcbb-3d808a6eea85
function ld_sistema!(dx,x,p,t)
  dx[1]= 3*x[1]+4*x[2]-sin(t) #se define la ecuación 1
  dx[2]=-x[1]+2*x[2]-t^2 #se define la ecuación 2
end

# ╔═╡ 76e043d6-94f2-4a57-b77b-0501531a53ed
begin
	p=1
