md"""
## $\cdot$ Ecuaciones de Lorenz """

# ╔═╡ 0b9975e6-e4fa-40ce-bf42-3a9c82cd1e59
md"""Las ecuaciones de Lorenz se utilizan como un modelo matemático para estudiar la convección atmosférica, que es el movimiento del aire en la atmósfera terrestre. El sistema modela tres variables $x$, $y$ y $z$, que representan las tasas de cambio de tres cantidades físicas relacionadas con la convección atmosférica. Por lo general, estas cantidades pueden interpretarse como la velocidad del flujo de aire en diferentes direcciones o las diferencias de temperatura entre diferentes regiones del aire.

Las ecuaciones de Lorenz son las siguientes

$\begin{align*}
\frac{dx}{dt} &= \sigma(y - x), \\
\frac{dy}{dt} &= x(\rho - z) - y, \\
\frac{dz}{dt} &= xy - \beta z,
\end{align*}$

donde $x$, $y$ y $z$ son las variables dinámicas, $t$ es el tiempo, y $\sigma$, $\rho$ y $\beta$ son parámetros que determinan las características del sistema.

Resolvamos dicho sistema de ecuaciones diferenciales considerando las siguientes condiciones iniciales

$x(0)=rLz, \quad y(0)=z(0)=0.$
"""

# ╔═╡ 15e62ee0-ea49-48c3-adba-2f0e6867a8a7
function parameterized_lorenz!(du,u,p,t) #definimos las EDOs
 du[1] = p[1]*(u[2]-u[1])
 du[2] = u[1]*(p[2]-u[3]) - u[2]
 du[3] = u[1]*u[2] - p[3]*u[3]
end

