md""" 
## $\cdot$ Pendulo doble 

Consideramos un sistema compuesto por dos péndulos acoplados. Cada péndulo tiene una masa $m_1$ y $m_2$, y con longitudes $l_1$ y $l_2$ respectivamente, y están sujetos a fuerzas de fricción $c_1$ y $c_2$ en sus movimientos. El péndulo 1 está conectado al punto de suspensión por un ángulo $y_1$, mientras que el péndulo 2 está conectado al péndulo 1 generando un ángulo $y_2$.

Cosideremos el siguiente sistema de ecuaciones diferenciales.
```math
   \begin{array}{lc}
\displaystyle     y''_1= \frac{A}{l_1(2m_1+m_2-m_2\cos(2y_1-2y_2)} -c_1y_1',   & \\
\displaystyle     y''_2= \frac{B}{l_2(2m_1+m_2-m_2\cos(2y_1-2y_2)} -c_2y_2'  \\
    y_1(t_0)=y_{10},  \quad   y'_1(t_0)=y_{11}.     & \\
    y_2(t_0)=y_{20},  \quad   y'_2(t_0)=y_{21}.     & \\
    \end{array}

donde
```
donde

```math
\begin{align*}
    A&=-g(2m_1+m_2)\sin(y_1)-m_2g\sin(y_1-2y_2),\\&-2\sin(y_1-y_2)m_2\Big(
     (y_2')^2l_2+(y_1')^2l_1\cos(y_1-y_2)\Big),
\end{align*}
```
y 
```math
\begin{align*}
    B&=2\sin(y_1-y_2)
    \Big( (y_1')^2l_1(m_1+m_2)+
    g(m_1+m_2)\cos(y_1),\\&+
    (y_2')^2l_2\cos(y_1-y_2) \Big).
\end{align*}
```

Las ecuaciones diferenciales describen las aceleraciones angulares $y''_1$ y $y''_2$ de los péndulos en función del tiempo $t$. Los parámetros $A$ y $B$ están definidos en función de las masas, longitudes, ángulos y velocidades angulares de los péndulos, así como de la aceleración debido a la gravedad $g$.

Note que las condiciones iniciales $y_1(t_0) = y_{10}$, $y'_1(t_0) = y_{11}$, $y_2(t_0) = y_{20}$ y $y'_2(t_0) = y_{21}$ nos indican las posiciones iniciales y velocidades angulares de los péndulos en el tiempo inicial $t_0$.

Podemos implementar este modelo como sigue. 
"""

# ╔═╡ fe01d117-0818-4a02-bbaf-bd4dcab207ec
function pdoble!(dx,x,p,t)
  M1,M2,L1,L2,G,c1,c2=p

  dx[1] = x[2]

  den1 = (M1+M2)*L1 - M2*L1*cos( x[3]-x[1])*cos(x[3]-x[1])
  T1= M2*L1*x[2]*x[2]*sin(x[3]-x[1])*cos(x[3]-x[1])
  T2=M2*G*sin(x[3])*cos(x[3]-x[1])
  T3=M2*L2*x[4]*x[4]*sin(x[3]-x[1])
  T4=(M1+M2)*G*sin(x[1]);

  dx[2] = (T1+T2+T3-T4)/den1-c1*x[2]
  dx[3]=x[4];

  den2=(L2/L1)*den1;

  T1= M2*L2*x[4]*x[4]*sin(x[3]-x[1])*cos(x[3]-x[1])
  T2=(M1+M2)*G*sin(x[1])*cos(x[3]-x[1]);
  T3=(M1+M2)*L1*x[2]*x[2]*sin(x[3]-x[1]);
  T4=(M1+M2)*G*sin(x[3]);

  dx[4]= (-T1+ T2-T3 - T4)/den2-c2*x[4];
end

