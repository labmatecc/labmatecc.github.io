	prob₁ = ODEProblem(f,u0,tspan₁) #Planteamos el problema a solucionar
	sol₁ = solve(prob₁) #lo solucionamos
end

# ╔═╡ aed74dae-ed6a-400c-84a2-2a89649a684a
