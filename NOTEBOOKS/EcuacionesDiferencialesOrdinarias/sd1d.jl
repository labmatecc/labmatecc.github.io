md"# $\cdot$ Interacción de especies: modelos depredador presa

Considere el sistema 

$$\left \{ \begin{array}{rcl]}
x'_1 &=&  -d x_1 +e x_1 x_2,\\
x'_2 &=& r \left(1 - \frac{x_2}{k}\right) x_2 - c  x_1 x_2.,\\
\end{array}\right.$$

con $x_1(0), x_2(0)$ dados. En este caso $x_1$ la población total de la especia especie 1  (depredador) y $x_2$ la catidad de población de la especie 2.


Resolvamos dicho sistema de ecuaciones diferenciales considerando las siguientes condiciones iniciales

$x_1(0)=80, \quad x_2(0)=100.$

"

# ╔═╡ 51c5bb79-805e-4e5f-9787-47f85fd43b5e
function predadorpresa!(du,u,p,t) #definimos las EDOs
 du[1] = -p[1]*u[1]+p[2]*u[1]*u[2]
 du[2] = p[3]*(1-u[2]/p[4])*u[2] - p[5]*u[1]*u[2]
end

